import { z } from "zod";

const linkSchema = z.object({
  id: z.string(),
  label: z.string(),
  href: z.string(),
  visible: z.boolean(),
});

const contentPageSchema = z.object({
  slug: z.string(),
  title: z.string(),
  content: z.string(),
  metaTitle: z.string(),
  metaDescription: z.string(),
  published: z.boolean(),
});

export const siteConfigSchema = z.object({
  brand: z.object({
    name: z.string(),
    tagline: z.string(),
    logoUrl: z.string(),
    logoLightUrl: z.string(),
    logoDarkUrl: z.string(),
    logoAlt: z.string(),
    faviconUrl: z.string(),
    description: z.string(),
    contactEmail: z.string(),
    phone: z.string(),
    address: z.string(),
    socialLinks: z.array(z.object({ platform: z.string(), url: z.string() })),
  }),
  seo: z.object({
    titleTemplate: z.string(),
    defaultTitle: z.string(),
    defaultDescription: z.string(),
  }),
  theme: z.object({
    colors: z.object({
      background: z.string(),
      foreground: z.string(),
      accent: z.string(),
      surface: z.string(),
    }),
    typography: z.object({ displayFont: z.string(), bodyFont: z.string() }),
    motionEnabled: z.boolean(),
  }),
  announcement: z.object({ enabled: z.boolean(), text: z.string(), href: z.string() }),
  header: z.object({ navigation: z.array(linkSchema) }),
  homepage: z.object({
    hero: z.object({
      enabled: z.boolean(),
      tagline: z.string(),
      heading: z.string(),
      subheading: z.string(),
      description: z.string(),
      primaryButtonText: z.string(),
      primaryButtonLink: z.string(),
      secondaryButtonText: z.string(),
      secondaryButtonLink: z.string(),
      backgroundImage: z.string(),
    }),
    featuredProducts: z.object({
      enabled: z.boolean(),
      tagline: z.string(),
      heading: z.string(),
      description: z.string(),
      ctaButtonText: z.string(),
      ctaButtonLink: z.string(),
      showPrices: z.boolean(),
      productsToShow: z.number().int().min(1),
      selectedProducts: z.array(z.string()),
    }),
    brandStory: z.object({
      enabled: z.boolean(),
      tagline: z.string(),
      heading: z.string(),
      paragraphs: z.array(z.string()),
      quote: z.string(),
      signature: z.string(),
      ctaButtonText: z.string(),
      ctaButtonLink: z.string(),
      image: z.string(),
    }),
    newsletter: z.object({
      enabled: z.boolean(),
      tagline: z.string(),
      heading: z.string(),
      description: z.string(),
      buttonText: z.string(),
      disclaimer: z.string(),
    }),
    sectionOrder: z.array(z.enum(["hero", "featuredProducts", "brandStory", "newsletter"])),
  }),
  footer: z.object({
    description: z.string(),
    linkGroups: z.array(z.object({ title: z.string(), links: z.array(linkSchema) })),
    legalLinks: z.array(linkSchema),
    copyright: z.string(),
    location: z.string(),
  }),
  contentPages: z.array(contentPageSchema),
  commerce: z.object({
    countryCode: z.literal("BD"),
    countryName: z.literal("Bangladesh"),
    currencyCode: z.literal("BDT"),
    currencySymbol: z.literal("৳"),
    taxRatePercent: z.number().min(0).max(100).nullable(),
    paymentMethods: z.object({
      cashOnDelivery: z.object({
        enabled: z.boolean(),
        fee: z.number().min(0).nullable(),
        minimumOrder: z.number().min(0).nullable(),
        maximumOrder: z.number().min(0).nullable(),
        restrictedAreas: z.array(z.string()),
      }),
      bkash: z.boolean(),
      nagad: z.boolean(),
      rocket: z.boolean(),
      upay: z.boolean(),
      uddoktaPay: z.boolean(),
    }),
    shipping: z.object({
      freeShippingThreshold: z.number().min(0).nullable(),
      zones: z.array(z.object({
        id: z.string(),
        name: z.string(),
        regions: z.array(z.string()),
        deliveryFee: z.number().min(0).nullable(),
        freeShippingThreshold: z.number().min(0).nullable(),
        estimatedDays: z.string(),
        enabled: z.boolean(),
      })),
      carriers: z.array(z.string()),
    }),
  }),
});

